/* ============================================================
   script.js  -  Weather Data Analysis Dashboard
   What this file does:
     1. Loads the JSON files that R created (results folder).
     2. Fills the dashboard cards and the analysis tables.
     3. Draws the Chart.js charts.
     4. Makes the menu, search box and dropdowns work.
   Nothing here is typed in by hand: every number comes from the JSON files.
   ============================================================ */

// Where the files are (relative to frontend/index.html)
const SUMMARY_URL = "../results/summary.json";
const CHART_URL   = "../results/chart_data.json";
const PREVIEW_URL = "../results/preview.json";

// Colours used in the charts
const BLUE = "#1e6fd9", LIGHT_BLUE = "rgba(30,111,217,0.25)", ORANGE = "#e8590c";
const PALETTE = ["#1e6fd9", "#4dabf7", "#74c0fc", "#339af0", "#1971c2", "#a5d8ff", "#228be6", "#0b3d91", "#91a7ff", "#5c7cfa"];

let previewData = { columns: [], rows: [] };   // used by the search box
const charts = {};                              // keeps the chart objects so we can update them

/* ---------- Small helper functions ---------- */
const $ = (id) => document.getElementById(id);

function showError(message) {
  const box = $("error-box");
  box.hidden = false;
  box.innerHTML = message;
}

// Load one JSON file. Throws a clear error if something goes wrong.
async function loadJSON(url) {
  let response;
  try {
    response = await fetch(url, { cache: "no-store" });
  } catch (err) {
    throw new Error("Could not read <code>" + url + "</code>. " +
      "If you opened index.html by double-clicking it, the browser blocks file loading. " +
      "Start the local server with <code>start_dashboard.bat</code> and open " +
      "<code>http://localhost:8000/frontend/index.html</code>.");
  }
  if (!response.ok) {
    throw new Error("<code>" + url + "</code> was not found (HTTP " + response.status + "). " +
      "Run the R analysis first: <code>Rscript R\\main_analysis.R</code>.");
  }
  return response.json();
}

// Number formatting
const fmt = (x, d = 2) => (x === null || x === undefined || Number.isNaN(x)) ? "-" : Number(x).toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d });
const fmtInt = (x) => Number(x).toLocaleString("en-US");

/* ---------- Build a table from a header list and row arrays ---------- */
function buildTable(tableId, headers, rows, numericFrom = 1, cellStyle) {
  const table = $(tableId);
  let html = "<thead><tr>" + headers.map((h, i) => `<th class="${i >= numericFrom ? "num" : ""}">${h}</th>`).join("") + "</tr></thead><tbody>";
  rows.forEach((row) => {
    html += "<tr>" + row.map((cell, i) => {
      const style = cellStyle ? cellStyle(cell, i) : "";
      return `<td class="${i >= numericFrom ? "num" : ""}" ${style ? `style="${style}"` : ""}>${cell}</td>`;
    }).join("") + "</tr>";
  });
  table.innerHTML = html + "</tbody>";
}

/* ---------- Dashboard cards ---------- */
function fillCards(s) {
  const c = s.cards;
  $("card-avg-temp").textContent = fmt(c.avg_temperature, 1) + " °C";
  $("card-max-temp").textContent = fmt(c.max_temperature, 1) + " °C";
  $("card-min-temp").textContent = fmt(c.min_temperature, 1) + " °C";
  $("card-avg-hum").textContent  = fmt(c.avg_humidity * 100, 1) + " %";     // humidity is stored as 0..1
  $("card-records").textContent  = fmtInt(c.total_records);

  if (c.total_rainfall === null || c.total_rainfall === undefined) {
    // This dataset has no rainfall amount, so we say so instead of inventing a number.
    $("card-rain").textContent = "Not available";
    $("card-rain").classList.add("small-value");
    $("card-rain-note").textContent = "The dataset has no rainfall-amount column.";
  } else {
    $("card-rain").textContent = fmt(c.total_rainfall, 1);
  }
  $("generated-by").textContent = "Results generated by: " + s.generated_by + " on " + s.generated_at + ".";

  // Hero + about text that depends on the data
  $("hero-records").textContent = fmtInt(s.dataset.rows_clean) + " hourly";
  $("hero-range").textContent = s.dataset.date_start + " to " + s.dataset.date_end;
  $("about-rows").textContent = fmtInt(s.dataset.rows_raw) + " raw hourly rows";
}

/* ---------- Analysis section ---------- */
function fillAnalysis(s) {
  const d = s.dataset;
  $("info-records").textContent = fmtInt(d.rows_clean);
  $("info-columns").textContent = d.columns;
  $("info-dates").textContent = d.date_start + " to " + d.date_end;
  $("info-dups").textContent = fmtInt(d.duplicates_removed);

  $("findings").innerHTML = s.findings.map((f) => `<li>${f}</li>`).join("");

  buildTable("missing-table",
    ["Column", "Missing in raw file", "Invalid zeros", "Missing after cleaning", "What was done"],
    s.missing_values.map((m) => [m.column, fmtInt(m.missing_in_raw_file), fmtInt(m.invalid_zeros_found), fmtInt(m.missing_after_cleaning), m.treatment]),
    1);
  // the last column is text, so left-align it
  document.querySelectorAll("#missing-table tr").forEach((tr) => tr.lastElementChild.classList.remove("num"));

  buildTable("stats-table",
    ["Variable", "Count", "Mean", "Median", "Mode", "Std Dev", "Variance", "Min", "Max"],
    s.statistics.map((r) => [r.variable, fmtInt(r.n), fmt(r.mean), fmt(r.median), fmt(r.mode), fmt(r.sd), fmt(r.variance), fmt(r.min), fmt(r.max)]),
    1);

  // Correlation table: blue = positive, orange = negative; stronger = darker
  const v = s.correlations.variables;
  buildTable("corr-table", [""].concat(v),
    s.correlations.matrix.map((row, i) => [v[i]].concat(row.map((x) => x === null ? "-" : x.toFixed(2)))),
    1,
    (cell, i) => {
      if (i === 0 || cell === "-") return "";
      const r = parseFloat(cell);
      const color = r >= 0 ? "30,111,217" : "232,89,12";
      return `background: rgba(${color}, ${Math.abs(r) * 0.55}); font-weight: 600;`;
    });
}

/* ---------- Dataset preview with search + column filter ---------- */
function setupPreview(p) {
  previewData = p;
  const select = $("column-select");
  select.innerHTML = '<option value="__all__">All columns</option>' +
    p.columns.map((c) => `<option value="${c}">${c}</option>`).join("");
  $("search-box").addEventListener("input", renderPreview);
  select.addEventListener("change", renderPreview);
  renderPreview();
}

function renderPreview() {
  const text = $("search-box").value.trim().toLowerCase();
  const column = $("column-select").value;
  const cols = previewData.columns;

  const rows = previewData.rows.filter((row) => {
    if (text === "") return true;
    const toCheck = column === "__all__" ? cols : [column];
    return toCheck.some((c) => String(row[c] ?? "").toLowerCase().includes(text));
  });

  buildTable("preview-table", cols,
    rows.map((row) => cols.map((c) => row[c] ?? "")), cols.length + 1);   // all cells left-aligned
  $("preview-count").textContent = "Showing " + rows.length + " of the first " + previewData.rows.length +
    " rows (the preview is limited to 200 rows so the page stays fast).";
}

/* ---------- Charts ---------- */
function drawChart(id, config) {
  if (typeof Chart === "undefined") {
    $(id).parentElement.innerHTML = '<div class="chart-msg">Chart.js could not be loaded (no internet?). ' +
      'Download chart.umd.min.js into <code>frontend/lib/</code> – see the README.</div>';
    return null;
  }
  if (charts[id]) charts[id].destroy();
  charts[id] = new Chart($(id), config);
  return charts[id];
}

const axisTitle = (text) => ({ display: true, text });

function drawCharts(c) {
  // 1. Temperature distribution (histogram as a bar chart)
  drawChart("chart-hist", {
    type: "bar",
    data: { labels: c.temperature_histogram.labels,
            datasets: [{ label: "Hours", data: c.temperature_histogram.counts, backgroundColor: BLUE, categoryPercentage: 1, barPercentage: 0.95 }] },
    options: { responsive: true, maintainAspectRatio: false, plugins: { legend: { display: false } },
               scales: { x: { title: axisTitle("Temperature range (°C)") }, y: { title: axisTitle("Number of hours") } } }
  });

  // 2. Temperature trend over time
  drawChart("chart-trend", {
    type: "line",
    data: { labels: c.monthly_temperature.labels,
            datasets: [{ label: "Average temperature (°C)", data: c.monthly_temperature.values, borderColor: BLUE,
                         backgroundColor: LIGHT_BLUE, fill: true, tension: 0.25, pointRadius: 0, pointHoverRadius: 4 }] },
    options: { responsive: true, maintainAspectRatio: false, interaction: { mode: "index", intersect: false },
               scales: { x: { title: axisTitle("Month"), ticks: { maxTicksLimit: 12 } }, y: { title: axisTitle("°C") } } }
  });

  // 3. Weather conditions (metric chosen with dropdown)
  const condLabels = { counts: "Number of hours", avg_temperature: "Average temperature (°C)", avg_humidity: "Average humidity (0 to 1)" };
  const drawCond = () => {
    const metric = $("cond-metric").value;
    drawChart("chart-cond", {
      type: "bar",
      data: { labels: c.weather_conditions.labels,
              datasets: [{ label: condLabels[metric], data: c.weather_conditions[metric], backgroundColor: PALETTE }] },
      options: { indexAxis: "y", responsive: true, maintainAspectRatio: false, plugins: { legend: { display: false } },
                 scales: { x: { title: axisTitle(condLabels[metric]) } } }
    });
  };
  $("cond-metric").onchange = drawCond;
  drawCond();

  // 4. Temperature vs humidity (scatter)
  $("scatter-note").textContent = c.temp_vs_humidity.note;
  const points = c.temp_vs_humidity.temperature.map((t, i) => ({ x: t, y: c.temp_vs_humidity.humidity[i] }));
  drawChart("chart-scatter", {
    type: "scatter",
    data: { datasets: [{ label: "Hourly record", data: points, backgroundColor: "rgba(30,111,217,0.35)", pointRadius: 2 }] },
    options: { responsive: true, maintainAspectRatio: false, plugins: { legend: { display: false } },
               scales: { x: { title: axisTitle("Temperature (°C)") }, y: { title: axisTitle("Humidity (0 to 1)"), min: 0, max: 1 } } }
  });

  // 5. Precipitation comparison. The dataset has the TYPE of precipitation, not the amount.
  $("rain-note").textContent = c.rainfall_available
    ? "Compares precipitation types."
    : "The dataset has no rainfall amount (mm), so this compares precipitation TYPES (rain / snow / unknown).";
  const precipLabels = { counts: "Number of hours", avg_temperature: "Average temperature (°C)",
                         avg_humidity: "Average humidity (0 to 1)", avg_wind_speed: "Average wind speed (km/h)" };
  const drawPrecip = () => {
    const metric = $("precip-metric").value;
    drawChart("chart-precip", {
      type: "bar",
      data: { labels: c.precipitation_types.labels,
              datasets: [{ label: precipLabels[metric], data: c.precipitation_types[metric], backgroundColor: ["#1e6fd9", "#74c0fc", "#adb5bd"] }] },
      options: { responsive: true, maintainAspectRatio: false, plugins: { legend: { display: false } },
                 scales: { y: { title: axisTitle(precipLabels[metric]) } } }
    });
  };
  $("precip-metric").onchange = drawPrecip;
  drawPrecip();

  // 6. Seasonal pattern (two lines, two y-axes)
  drawChart("chart-season", {
    type: "line",
    data: { labels: c.seasonal_pattern.labels,
            datasets: [
              { label: "Avg temperature (°C)", data: c.seasonal_pattern.avg_temperature, borderColor: BLUE, backgroundColor: BLUE, yAxisID: "y", tension: 0.3 },
              { label: "Avg humidity (0 to 1)", data: c.seasonal_pattern.avg_humidity, borderColor: ORANGE, backgroundColor: ORANGE, yAxisID: "y1", tension: 0.3 } ] },
    options: { responsive: true, maintainAspectRatio: false, interaction: { mode: "index", intersect: false },
               scales: { y: { position: "left", title: axisTitle("°C") },
                         y1: { position: "right", title: axisTitle("Humidity"), grid: { drawOnChartArea: false } } } }
  });
}

/* ---------- Conclusion (written from the loaded numbers) ---------- */
function writeConclusion(s, c) {
  const t = c.seasonal_pattern.avg_temperature;
  const names = c.seasonal_pattern.labels;
  const hot = t.indexOf(Math.max(...t)), cold = t.indexOf(Math.min(...t));
  const vars = s.correlations.variables;
  const r = s.correlations.matrix[vars.indexOf("Temperature (C)")][vars.indexOf("Humidity")];
  $("conclusion").textContent =
    `After cleaning, ${fmtInt(s.dataset.rows_clean)} hourly records were analysed. The average temperature is ${fmt(s.cards.avg_temperature, 1)} °C, ` +
    `with a clear yearly cycle: ${names[hot]} is the warmest month on average (${fmt(t[hot], 1)} °C) and ${names[cold]} the coldest (${fmt(t[cold], 1)} °C). ` +
    `Temperature and humidity are ${r < 0 ? "negatively" : "positively"} correlated (r = ${fmt(r)}). ` +
    `Cleaning mattered: impossible zero readings in pressure and humidity were removed so they would not distort the statistics. ` +
    `Because the dataset has no rainfall amounts, rainfall totals could not be calculated.`;
}

/* ---------- Navigation ---------- */
function setupNavigation() {
  const links = $("nav-links");
  $("menu-btn").addEventListener("click", () => links.classList.toggle("open"));
  links.querySelectorAll("a").forEach((a) => a.addEventListener("click", () => links.classList.remove("open")));

  // Highlight the link of the section that is on screen
  const sections = ["home", "dashboard", "analysis", "charts", "about"].map((id) => $(id));
  window.addEventListener("scroll", () => {
    let current = "home";
    sections.forEach((sec) => { if (sec.getBoundingClientRect().top <= 100) current = sec.id; });
    links.querySelectorAll("a").forEach((a) => a.classList.toggle("active", a.getAttribute("href") === "#" + current));
  });
}

/* ---------- Start everything ---------- */
async function init() {
  setupNavigation();
  try {
    const [summary, chartData, preview] = await Promise.all([loadJSON(SUMMARY_URL), loadJSON(CHART_URL), loadJSON(PREVIEW_URL)]);
    fillCards(summary);
    fillAnalysis(summary);
    setupPreview(preview);
    drawCharts(chartData);
    writeConclusion(summary, chartData);
  } catch (err) {
    showError("<b>Could not load the analysis results.</b><br>" + err.message);
    $("conclusion").textContent = "Conclusion unavailable because the results could not be loaded.";
  }
}
init();
