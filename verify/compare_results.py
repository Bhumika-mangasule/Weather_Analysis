r"""
compare_results.py - checks that the numbers made by R match the Python check.

Steps (from the project folder):
  1. Rscript R\main_analysis.R                              (creates results\*.json)
  2. python verify\python_reference.py --out verify\python_output
  3. python verify\compare_results.py
"""
import json, sys

def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)

R = load("results/summary.json"); P = load("verify/python_output/summary.json")
RC = load("results/chart_data.json"); PC = load("verify/python_output/chart_data.json")
problems = []

def close(a, b, tol=1e-3):
    if a is None or b is None:
        return a is b
    return abs(a - b) <= tol * max(1.0, abs(b))

for k in P["cards"]:
    if not close(R["cards"].get(k), P["cards"][k]):
        problems.append(f"card {k}: R={R['cards'].get(k)} Python={P['cards'][k]}")
for rs, ps in zip(R["statistics"], P["statistics"]):
    for k in ("n", "mean", "median", "mode", "sd", "variance", "min", "max"):
        if not close(rs[k], ps[k]):
            problems.append(f"{ps['variable']} {k}: R={rs[k]} Python={ps[k]}")
for i, (a, b) in enumerate(zip(R["correlations"]["matrix"], P["correlations"]["matrix"])):
    for j, (x, y) in enumerate(zip(a, b)):
        if not close(x, y, 2e-3):
            problems.append(f"correlation [{i}][{j}]: R={x} Python={y}")
for key in ("temperature_histogram", "monthly_temperature", "seasonal_pattern", "weather_conditions", "precipitation_types"):
    for sub in PC[key]:
        a, b = RC[key][sub], PC[key][sub]
        same = (a == b) if isinstance(b[0], str) else (len(a) == len(b) and all(close(x, y) for x, y in zip(a, b)))
        if not same:
            problems.append(f"chart_data {key}.{sub} differs")
if len(RC["temp_vs_humidity"]["temperature"]) != len(PC["temp_vs_humidity"]["temperature"]):
    problems.append("scatter sample size differs")

print("results/ generated by:", R["generated_by"])
if not R["generated_by"].startswith("R "):
    print("WARNING: results/ was NOT made by R. Run  Rscript R\\main_analysis.R  first, then compare again.")
if problems:
    print("DIFFERENCES FOUND:"); [print(" -", p) for p in problems]; sys.exit(1)
print("OK - R results match the independent Python check.")
